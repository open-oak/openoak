import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apps = JSON.parse(await readFile(path.join(root, "shared/pwa/apps.json"), "utf8"));
const worker = await readFile(path.join(root, "shared/pwa/service-worker.js"), "utf8");
const css = await readFile(path.join(root, "shared/pwa/offline.css"), "utf8");
const check = process.argv.includes("--check");

for (const [app, config] of Object.entries(apps)) {
  const directory = path.join(root, "apps", app, "public");
  const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
    <meta name="theme-color" content="#f5f5f5">
    <title>${config.name} offline</title>
    <link rel="stylesheet" href="/offline.css">
    <link rel="icon" href="/icon-192.png">
    <link rel="apple-touch-icon" href="/apple-touch-icon.png">
    <link rel="manifest" href="/manifest.webmanifest">
  </head>
  <body>
    <main>
      <img src="/icon-192.png" alt="" width="80" height="80">
      <h1>${config.name} is offline</h1>
      <p>${config.offlineMessage}</p>
      <a href="/">${app === "kanban" ? "Open saved boards" : "Try connecting again"}</a>
    </main>
  </body>
</html>
`;
  const hash = createHash("sha256").update(worker + html + css + JSON.stringify(config));
  for (const icon of ["icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png"]) {
    hash.update(await readFile(path.join(directory, icon)));
  }
  const version = hash.digest("hex").slice(0, 12);
  const script = `// Generated by scripts/generate-pwa.mjs.\nconst CONFIG = ${JSON.stringify({ prefix: `openoak-${app}-pwa-`, version, boardShell: app === "kanban", legacyCaches: config.legacyCaches })};\n${worker}`;
  const files = { [config.worker.slice(1)]: script, "offline.html": html, "offline.css": css };
  if (!check) await mkdir(directory, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(directory, name);
    if (check) {
      if (await readFile(file, "utf8") !== content) throw new Error(`${file} is stale. Run npm run generate:pwa.`);
    } else await writeFile(file, content);
  }
}
console.log(check ? "PWA workers and offline pages are current." : "Generated PWA workers and offline pages for all four apps.");
