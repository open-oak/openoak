const endpoint = (process.env.MCP_BENCHMARK_URL || "https://mcp.openoak.org").replace(/\/$/, "");
const token = process.env.MCP_BENCHMARK_TOKEN || "";
const samples = Number(process.env.MCP_BENCHMARK_SAMPLES || 20);
const allowWrites = process.env.MCP_BENCHMARK_ALLOW_WRITES === "true";
let requestId = 0;

if (!Number.isSafeInteger(samples) || samples < 20 || samples > 100) {
  throw new Error("MCP_BENCHMARK_SAMPLES must be an integer from 20 through 100.");
}

function meta() {
  return {
    "io.modelcontextprotocol/protocolVersion": "2026-07-28",
    "io.modelcontextprotocol/clientCapabilities": {},
    "io.modelcontextprotocol/clientInfo": { name: "openoak-benchmark", version: "1" },
  };
}

async function rpc(method, params = {}, name) {
  const id = ++requestId;
  const started = performance.now();
  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      accept: "application/json",
      authorization: `Bearer ${token}`,
      "content-type": "application/json",
      "mcp-method": method,
      "mcp-protocol-version": "2026-07-28",
      ...(name ? { "mcp-name": name } : {}),
    },
    body: JSON.stringify({ jsonrpc: "2.0", id, method, params: { ...params, _meta: meta() } }),
  });
  const durationMs = performance.now() - started;
  const payload = await response.json().catch(() => ({}));
  if (!response.ok || payload.error) {
    throw new Error(`${method}${name ? `:${name}` : ""} failed (${response.status}): ${JSON.stringify(payload.error || payload)}`);
  }
  return { durationMs, payload };
}

function tool(name, args = {}) {
  return rpc("tools/call", { name, arguments: args }, name);
}

function structured(result) {
  return result.payload?.result?.structuredContent || {};
}

function percentile(values, fraction) {
  const ordered = [...values].sort((a, b) => a - b);
  return ordered[Math.max(0, Math.ceil(ordered.length * fraction) - 1)];
}

const report = [];
async function measure(name, budgetMs, operation) {
  const cold = await operation();
  const values = [];
  for (let index = 0; index < samples; index += 1) values.push((await operation()).durationMs);
  const p95 = percentile(values, 0.95);
  const passed = p95 < budgetMs && cold.durationMs < 3_000;
  report.push({ name, samples, coldMs: Math.round(cold.durationMs), p95Ms: Math.round(p95), budgetMs, passed });
}

if (!token) {
  throw new Error("Set MCP_BENCHMARK_TOKEN to a short-lived token for the dedicated MCP test account.");
}

await measure("discovery", 300, () => rpc("server/discover"));
await measure("connection-status", 1_000, () => tool("openoak_connection_status"));
await measure("paginated-read", 1_500, () => tool("todo_list_lists", { limit: 20 }));
await measure("cross-product-search", 1_500, () => tool("openoak_search", {
  query: `openoak-benchmark-${new Date().toISOString().slice(0, 10)}`,
  limit: 20,
}));

const noteId = process.env.MCP_BENCHMARK_OUTLINE_NOTE_ID;
if (noteId) await measure("detailed-read", 1_500, () => tool("outline_get_note", { id: noteId }));

if (allowWrites) {
  await measure("disposable-mutation", 2_000, async () => {
    const created = await tool("outline_create_note", {
      title: `Disposable MCP benchmark ${Date.now()}`,
      body: "Safe to delete: generated by the OpenOak MCP latency benchmark.",
    });
    const note = structured(created);
    const deleted = await tool("outline_delete_note", { id: note.id, expectedUpdatedAt: note.updatedAt });
    return { durationMs: created.durationMs + deleted.durationMs, payload: deleted.payload };
  });
}

console.table(report);
if (report.some((item) => !item.passed)) process.exitCode = 1;
